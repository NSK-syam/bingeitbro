type AdminSeed = {
  id: string;
  title: string;
  year: number;
  type: Recommendation['type'];
  language: string;
  tmdbId: number;
  posterPath: string;
  backdropPath: string;
  personalNote: string;
  service?: string;
  franchise?: string;
};

export type AdminRecommendation = Recommendation & {
  franchise?: string;
};

const imageUrl = (path: string, size: 'w500' | 'w780' | 'original' = 'w500') =>
  `${TMDB_IMAGE_BASE}/${size}${path}`;

const adminProfile = {
  id: 'admin-curated',
  name: "Admin's Desk",
  avatar: '',
};

const toRecommendation = (seed: AdminSeed): AdminRecommendation => {
  const id = seed.type === 'series' ? `tmdbtv-${seed.tmdbId}` : `tmdb-${seed.tmdbId}`;

  return {
    id,
    title: seed.title,
    year: seed.year,
    type: seed.type,
    poster: imageUrl(seed.posterPath),
    backdrop: imageUrl(seed.backdropPath, 'original'),
    genres: [],
    language: seed.language,
    duration: undefined,
    rating: undefined,
    recommendedBy: adminProfile,
    personalNote: seed.personalNote,
    mood: [],
    watchWith: undefined,
    ottLinks: seed.service
      ? [
          {
            platform: seed.service,
            url: seed.type === 'series' ? `/show/${id}` : `/movie/${id}`,
            logoPath: PROVIDER_LOGO_MAP[seed.service] || '',
          },
        ]
      : [],
    addedOn: '2026-03-01T00:00:00.000Z',
    franchise: seed.franchise,
  };
};

const sortByYear = (items: AdminRecommendation[]) =>
  [...items].sort((a, b) => (a.year - b.year) || a.title.localeCompare(b.title));

